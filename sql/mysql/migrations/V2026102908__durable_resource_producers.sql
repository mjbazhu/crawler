-- 生成任务独立于文件传输；父 task 已冻结来源/目标身份，禁止正文或临时路径进入计划。
CREATE TABLE IF NOT EXISTS resource_producer_tasks (
    producer_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    parent_operation_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    parent_task_id BIGINT UNSIGNED NOT NULL,
    destination VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    processor_version VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    schema_version INT UNSIGNED NOT NULL,
    state VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'pending',
    claim_generation BIGINT UNSIGNED NOT NULL DEFAULT 0,
    claimed_at BIGINT UNSIGNED NOT NULL DEFAULT 0,
    available_at BIGINT UNSIGNED NOT NULL DEFAULT 0,
    attempt_count INT UNSIGNED NOT NULL DEFAULT 0,
    cancel_requested TINYINT UNSIGNED NOT NULL DEFAULT 0,
    timeout_ms INT UNSIGNED NOT NULL,
    retries INT UNSIGNED NOT NULL,
    max_bytes BIGINT UNSIGNED NOT NULL,
    bytes_per_second BIGINT UNSIGNED NOT NULL DEFAULT 0,
    result_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '',
    error_category VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '',
    child_operation_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '',
    created_at BIGINT UNSIGNED NOT NULL,
    updated_at BIGINT UNSIGNED NOT NULL,
    PRIMARY KEY (producer_id),
    UNIQUE KEY uk_producer_parent_task (parent_task_id),
    KEY idx_producer_dispatch (destination,state,available_at,producer_id),
    KEY idx_producer_parent_operation (parent_operation_id,producer_id),
    CONSTRAINT fk_producer_parent_task FOREIGN KEY (parent_task_id) REFERENCES resource_transfer_tasks(task_id) ON DELETE CASCADE,
    CONSTRAINT ck_producer_destination CHECK (destination IN ('local','baidu','gdrive')),
    CONSTRAINT ck_producer_state CHECK (state IN ('pending','waiting_input','running','retry','succeeded','failed','cancelled','blocked')),
    CONSTRAINT ck_producer_budget CHECK (timeout_ms BETWEEN 100 AND 600000 AND retries<=5 AND max_bytes>0 AND max_bytes<=1073741824 AND schema_version>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
