CREATE TABLE IF NOT EXISTS `song_resources` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '资源记录主键',
  `song_source_ref_id` bigint unsigned NOT NULL COMMENT '关联 song_source_refs.id，表示该资源来自哪个平台来源',
  `resource_kind` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '资源类型，例如 audio、cover、lyric、mrc',
  `format_type` varchar(16) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT '' COMMENT '音频资源的音质档位，例如 PQ、HQ；非音频资源使用空字符串',
  `local_path` text COLLATE utf8mb4_unicode_ci COMMENT '资源保存到本地文件系统后的相对或绝对路径',
  `cloud_backend` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT '' COMMENT '云端上传后端，例如 baidupcs；未上传时为空',
  `cloud_path` text COLLATE utf8mb4_unicode_ci COMMENT '资源上传到云端网盘后的稳定路径',
  `size_bytes` bigint unsigned NOT NULL DEFAULT '0' COMMENT '本地已保存资源大小，单位字节；未知或未下载时为 0',
  `checksum` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '本地资源校验值，例如 SHA-256；未计算时为空',
  `status` tinyint NOT NULL DEFAULT '0' COMMENT '资源状态：0 待获取，1 获取中，2 已完成，3 失败，4 跳过',
  `retry_count` int unsigned NOT NULL DEFAULT '0' COMMENT '资源获取重试次数',
  `last_error` text COLLATE utf8mb4_unicode_ci COMMENT '最近一次资源获取失败原因，需脱敏后写入',
  `error_category` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '资源失败分类：network、parse、persistence、copyright、resource、invalid_target、timeout、unknown',
  `result_code` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '资源结果编码：ok、network_failed、parse_failed、persist_failed、invalid_target、timeout、partial_completed、failed',
  `last_batch_id` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '最近处理该资源任务的批次 ID',
  `running_batch_id` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '正在处理该资源任务的批次 ID',
  `claim_generation` bigint unsigned NOT NULL DEFAULT '0' COMMENT '资源认领代次，回写必须匹配',
  `last_processed_at` bigint unsigned NOT NULL DEFAULT '0' COMMENT '最近治理或处理时间，Unix 秒时间戳',
  `fetched_at` bigint unsigned NOT NULL DEFAULT '0' COMMENT '资源最近一次成功获取时间，Unix 秒时间戳',
  `cloud_uploaded_at` bigint unsigned NOT NULL DEFAULT '0' COMMENT '资源最近一次成功上传到云端的时间，Unix 秒时间戳',
  `created_at` bigint unsigned NOT NULL DEFAULT '0' COMMENT '记录创建时间，Unix 秒时间戳',
  `updated_at` bigint unsigned NOT NULL DEFAULT '0' COMMENT '记录最后更新时间，Unix 秒时间戳',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_resource` (`song_source_ref_id`,`resource_kind`,`format_type`),
  KEY `idx_resource_status` (`status`),
  KEY `idx_resource_kind` (`resource_kind`),
  KEY `idx_resource_fetch_order` (`status`,`retry_count`,`updated_at`),
  KEY `idx_resource_error_category` (`error_category`,`result_code`,`status`),
  KEY `idx_resource_queue_page` (`updated_at`,`id`),
  KEY `idx_resource_queue_status_page` (`status`,`updated_at`,`id`),
  CONSTRAINT `fk_song_resources_ref` FOREIGN KEY (`song_source_ref_id`) REFERENCES `song_source_refs` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='歌曲资源表，保存封面、歌词、音频等资源的获取任务和本地保存结果';
