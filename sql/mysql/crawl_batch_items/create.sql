CREATE TABLE IF NOT EXISTS `crawl_batch_items` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '采集批次目标本地主键',
  `batch_id` varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '关联 crawl_batches.batch_id',
  `item_index` int unsigned NOT NULL COMMENT '目标在批次内的顺序，从 0 开始',
  `item_key` varchar(256) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '目标业务键，例如 singer:112、album:600927015009001083',
  `item_type` varchar(64) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '目标类型：singerIndexTab、singerSongs、singerAlbums、albumDetail、albumSongs',
  `item_label` varchar(512) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '前端展示名称，例如歌手 ID、分类 tab、专辑标题',
  `source` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'migu' COMMENT '音乐平台标识，例如 migu',
  `source_singer_id` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '平台歌手 ID',
  `source_album_id` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '平台专辑 ID',
  `source_song_id` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '平台歌曲 ID；当前预留给后续资源任务',
  `state` varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'Pending' COMMENT '目标状态：Pending、Running、Completed、Failed、Cancelled',
  `retry_count` int unsigned NOT NULL DEFAULT '0' COMMENT '目标已重试次数',
  `written_count` int unsigned NOT NULL DEFAULT '0' COMMENT '该目标写入或解析出的记录数量；未知时为 0',
  `error_category` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '失败分类：network、parse、persistence、copyright、resource、invalid_target、timeout、unknown',
  `result_code` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '结果编码：ok、network_failed、parse_failed、persist_failed、partial_completed',
  `started_at` bigint unsigned NOT NULL DEFAULT '0' COMMENT '目标开始时间，Unix 秒时间戳',
  `finished_at` bigint unsigned NOT NULL DEFAULT '0' COMMENT '目标结束时间，Unix 秒时间戳；0 表示未结束',
  `last_error` text COLLATE utf8mb4_unicode_ci COMMENT '目标最近失败原因，需脱敏',
  `payload` json DEFAULT NULL COMMENT '目标额外上下文，例如 source_res_type、source_album_kind',
  `created_at` bigint unsigned NOT NULL DEFAULT '0' COMMENT '创建时间，Unix 秒时间戳',
  `updated_at` bigint unsigned NOT NULL DEFAULT '0' COMMENT '更新时间，Unix 秒时间戳',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_crawl_batch_item_index` (`batch_id`,`item_index`),
  KEY `idx_crawl_batch_items_batch_state` (`batch_id`,`state`,`item_index`),
  KEY `idx_crawl_batch_items_type_state` (`source`,`item_type`,`state`,`updated_at`),
  KEY `idx_crawl_batch_items_singer` (`source`,`source_singer_id`),
  KEY `idx_crawl_batch_items_album` (`source`,`source_album_id`),
  KEY `idx_crawl_batch_items_singer_type_state` (`source`,`source_singer_id`,`item_type`,`state`,`updated_at`,`id`),
  CONSTRAINT `fk_crawl_batch_items_batch` FOREIGN KEY (`batch_id`) REFERENCES `crawl_batches` (`batch_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='采集批次目标表，记录每个歌手、分类或专辑的执行状态';
