CREATE TABLE IF NOT EXISTS `album_resources` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '封面资源主键',
  `album_source_ref_id` bigint unsigned NOT NULL COMMENT '资源所属来源主键',
  `resource_kind` varchar(16) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'cover' COMMENT '资源类型，当前为封面',
  `remote_url` text COLLATE utf8mb4_unicode_ci COMMENT '采集响应中的图片地址，供后续独立下载',
  `local_path` text COLLATE utf8mb4_unicode_ci COMMENT '模块内相对存储路径',
  `size_bytes` bigint unsigned NOT NULL DEFAULT '0' COMMENT '实际保存字节数',
  `checksum` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '完整文件校验值',
  `status` tinyint NOT NULL DEFAULT '0' COMMENT '0 待获取，1 获取中，2 已完成，3 失败',
  `error_category` varchar(64) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT '' COMMENT '失败分类',
  `result_code` varchar(64) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT '' COMMENT '处理结果码',
  `last_error` text COLLATE utf8mb4_unicode_ci COMMENT '脱敏失败原因',
  `fetched_at` bigint unsigned NOT NULL DEFAULT '0' COMMENT '成功保存时间',
  `created_at` bigint unsigned NOT NULL DEFAULT '0' COMMENT '创建时间',
  `updated_at` bigint unsigned NOT NULL DEFAULT '0' COMMENT '更新时间',
  `claim_generation` bigint unsigned NOT NULL DEFAULT 0 COMMENT '独立封面下载认领代次',
  `running_batch_id` varchar(128) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '当前下载批次',
  `claimed_at` bigint unsigned NOT NULL DEFAULT 0 COMMENT '独立下载认领时间',
  `cloud_backend` VARCHAR(32) NOT NULL DEFAULT '',
  `cloud_path` TEXT DEFAULT NULL,
  `cloud_size_bytes` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `cloud_checksum` VARCHAR(128) NOT NULL DEFAULT '',
  `cloud_status` TINYINT NOT NULL DEFAULT 0 COMMENT '0 待上传，1 运行中，2 已确认，3 失败，4 待核对',
  `cloud_uploaded_at` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `cloud_claim_generation` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `cloud_claimed_at` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `cloud_running_batch_id` VARCHAR(128) DEFAULT NULL,
  `cloud_error_category` VARCHAR(64) NOT NULL DEFAULT '',
  `cloud_result_code` VARCHAR(64) NOT NULL DEFAULT '',
  `cloud_last_error` TEXT DEFAULT NULL,
  `cloud_attempt` JSON DEFAULT NULL,
  KEY `idx_album_resources_cloud_queue` (`status`,`cloud_status`,`updated_at`,`id`),
  KEY `idx_album_resources_download_queue` (`status`,`updated_at`,`id`),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_album_resources_owner` (`album_source_ref_id`,`resource_kind`),
  CONSTRAINT `fk_album_resources_owner` FOREIGN KEY (`album_source_ref_id`) REFERENCES `album_source_refs` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='封面地址与本地保存结果，采集阶段只登记地址';
